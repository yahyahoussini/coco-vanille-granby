const COPY = { fr, en, es }

export const CHAT_LOCALES = ['fr', 'en', 'es']
export const chatLocale = (l) => (CHAT_LOCALES.includes(l) ? l : 'fr')
export const chatCopy = (locale) => COPY[chatLocale(locale)]

// Error text for the JSON answers of /svc/clavardage/: { fr, en, es } so the widget shows its own language.
export function errorText(code) {
  const key = code in fr.errors ? code : 'invalid'
  return { fr: fr.errors[key], en: en.errors[key], es: es.errors[key] }
}
